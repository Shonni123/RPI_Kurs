def seed_database():
    print("Clearing old flights...")
    Flight.objects.all().delete()
    print("Seeding new clean, diverse flights...")
    flights_data = get_diverse_flights_data()
    for item in flights_data:
        Flight.objects.create(**item)
    print(f"Successfully seeded {len(flights_data)} authentic diverse flights.")

    # Update airport counts to match exact flights
    print("Recalculating airport departures and arrivals counts...")
    for apt in Airport.objects.all():
        apt.departures_count = Flight.objects.filter(from_code=apt.code).count()
        apt.arrivals_count = Flight.objects.filter(to_code=apt.code).count()
        apt.save()
    print("Airport statistics synchronized.")

if __name__ == '__main__':
    seed_database()

